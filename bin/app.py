def get_available_primers(outdir):
    consensus_dir = Path(outdir) / "consensus"
    if not consensus_dir.exists():
        return []
    return sorted([f.name.replace(".cluster_consensus.tsv", "") for f in consensus_dir.glob("*.cluster_consensus.tsv")])

@st.cache_data
def load_tsv_files(outdir, primer):
    """
    Loads all the consensus TSV files generated by the crabs/vsearch steps.
    These files represent 'Spreadsheet 2' (The Name Tag) which assigns 
    a taxonomy (species/genus/etc.) to each clustered sequence.
    """
    consensus_dir = Path(outdir) / "consensus"
    file = consensus_dir / f"{primer}.cluster_consensus.tsv"
    
    if not file.exists():
        return pd.DataFrame(columns=COLUMNS + ["primer"])
        
    tmp = pd.read_csv(
        file,
        sep="\t",
        header=None,
        names=COLUMNS,
        dtype=DTYPES
    )
    tmp["accession_name"] = "Unknown"
    tmp["primer"] = primer

    return tmp

@st.cache_data
def get_seqs_per_cluster(df):
    if df.empty:
        return pd.DataFrame()
    return (
        df.groupby(["primer", "cluster_id"], dropna=False)
        .agg(
            sequence_count=("accession", "count"),
            unique_accession_taxids=("accession_taxid", "nunique"),
            assigned_taxid=("assigned_taxid", "first"),
            assigned_rank=("assigned_rank", "first"),
            assigned_name=("assigned_name", "first")
        )
        .reset_index()
        .sort_values("sequence_count", ascending=False)
    )

@st.cache_data
def get_basic_metrics(df):
    if df.empty:
        return 0, 0, 0, 0
    total_clusters = df["cluster_id"].nunique()
    total_accessions = df["accession"].nunique()
    total_accession_taxids = df["accession_taxid"].nunique()
    total_assigned_taxids = df["assigned_taxid"].nunique()
    return total_clusters, total_accessions, total_accession_taxids, total_assigned_taxids

@st.cache_data
def get_primer_summary(df, seqs_per_cluster):
    if df.empty:
        return pd.DataFrame()
    primer_summary = (
        df.groupby("primer")
        .agg(
            total_rows=("accession", "count"),
            total_clusters=("cluster_id", "nunique"),
            total_accessions=("accession", "nunique"),
            unique_accession_taxids=("accession_taxid", "nunique"),
            unique_assigned_taxids=("assigned_taxid", "nunique")
        )
        .reset_index()
    )
    primer_rank_mode = (
        seqs_per_cluster.groupby("primer")["assigned_rank"]
        .apply(lambda x: x.dropna().mode().iloc[0] if not x.dropna().mode().empty else "NA")
        .reset_index(name="most_common_rank")
    )
    return primer_summary.merge(primer_rank_mode, on="primer", how="left")

@st.cache_data
def get_taxon_counts(seqs_per_cluster):
    if seqs_per_cluster.empty:
        return pd.DataFrame()
    taxon_counts = (
        seqs_per_cluster
        .groupby(["assigned_taxid", "assigned_rank"], dropna=False)
        .agg(
            count=("cluster_id", "count"),
            assigned_name=("assigned_name", "first")
        )
        .reset_index()
        .sort_values("count", ascending=False)
    )
    taxon_counts["clean_name"] = taxon_counts.apply(
        lambda row: clean_taxon_name(row["assigned_name"], row["assigned_rank"]),
        axis=1
    )
    taxon_counts["plot_name"] = taxon_counts.apply(
        lambda row: f'{row["assigned_taxid"]} | {shorten(row["clean_name"], 30)}',
        axis=1
    )
    return taxon_counts

@st.cache_data
def get_resolution(seqs_per_cluster):
    if seqs_per_cluster.empty:
        return pd.DataFrame(), pd.DataFrame()
    resolution = (
        seqs_per_cluster
        .groupby(["primer", "assigned_rank"], dropna=False)
        .agg(cluster_count=("cluster_id", "count"))
        .reset_index()
    )
    primer_totals = (
        seqs_per_cluster
        .groupby("primer")
        .agg(total_clusters=("cluster_id", "count"))
        .reset_index()
    )
    resolution = resolution.merge(primer_totals, on="primer")
    resolution["pct"] = (
        resolution["cluster_count"] / resolution["total_clusters"] * 100
    ).round(1)
    resolution["assigned_rank"] = resolution["assigned_rank"].fillna("unresolved")
    return resolution, primer_totals

@st.cache_data
def get_merged_len(filtered_len, df):
    filtered_len = filtered_len.copy()
    filtered_len["accession"] = filtered_len["header"].str.split().str[0]
    merged_len = pd.merge(filtered_len, df[["accession", "assigned_name", "assigned_rank"]].drop_duplicates(), on="accession", how="inner")
    return merged_len

@st.cache_data
def get_teeliste_results(df, teeliste_df, taxids_db_df, selected_primer):
    taxids = teeliste_df["taxid"].astype(str).str.strip()

    # Clean each needed column once and reuse it, instead of re-stripping
    # the same columns over and over for every lookup map below.
    cluster_id = df["cluster_id"]
    acc_taxid = df["accession_taxid"].astype(str).str.strip()
    assigned_taxid = df["assigned_taxid"].astype(str).str.strip()
    assigned_rank = df["assigned_rank"].astype(str).str.strip()
    assigned_name = df["assigned_name"].astype(str).str.strip()
    db_taxid = taxids_db_df["taxid"].astype(str).str.strip()
    db_count = taxids_db_df["count"].astype(str).str.strip()

    def join_sorted_unique(values, keys):
        return pd.Series(values.values, index=keys.values).groupby(level=0).agg(
            lambda x: ";".join(sorted(set(x)))
        )

    accession_counts = acc_taxid.value_counts()
    assigned_counts = (
        pd.DataFrame({"cluster_id": cluster_id, "assigned_taxid": assigned_taxid})
        .drop_duplicates()
        .groupby("assigned_taxid")["cluster_id"]
        .nunique()
    )
    assigned_rank_map = join_sorted_unique(assigned_rank, assigned_taxid)
    assigned_name_map = join_sorted_unique(assigned_name, assigned_taxid)
    db_count_map = join_sorted_unique(db_count, db_taxid)

    accession_to_assigned_name_map = join_sorted_unique(assigned_name, acc_taxid)
    accession_to_assigned_taxid_map = join_sorted_unique(assigned_taxid, acc_taxid)
    accession_to_assigned_rank_map = join_sorted_unique(assigned_rank, acc_taxid)

    results_df = pd.DataFrame({
        "taxid": taxids,
        "german_name": teeliste_df["german_name"],
        "latin_name": teeliste_df["latin_name"],
        "no_of_occurance": taxids.map(accession_counts).fillna(0).astype(int),
        "LCA_which_resolved_to_this_taxid": taxids.map(assigned_counts).fillna(0).astype(int),
        "name_of_the_lca_taxid": taxids.map(assigned_name_map).fillna("not_assigned"),
        "name_of_the_lca_rank": taxids.map(assigned_rank_map).fillna("NA"),
        "consensus_name": taxids.map(accession_to_assigned_name_map).fillna("not_found"),
        "consensus_taxid": taxids.map(accession_to_assigned_taxid_map).fillna("not_found"),
        "consensus_rank": taxids.map(accession_to_assigned_rank_map).fillna("not_found"),
        "db_count": taxids.map(db_count_map).fillna("0"),
    })

    results_df["amplified"] = ((results_df["no_of_occurance"] > 0) | (results_df["LCA_which_resolved_to_this_taxid"] > 0)).map({True: "yes", False: "no"})
    results_df["taxid"] = results_df["taxid"].astype(str).str.strip()
    results_df["primer"] = selected_primer
    return results_df


def most_common(series, default="NA"):
    series = series.dropna()
    return series.value_counts().idxmax() if len(series) > 0 else default


def clean_taxon_name(name, rank=None):
    if pd.isna(name):
        return "Unknown"

    name = str(name).split(";")[0].strip()

    if rank == "genus":
        return name.split()[0] if name else "Unknown"

    if rank == "species":
        parts = name.split()
        return " ".join(parts[:2]) if len(parts) >= 2 else name

    return name


def shorten(text, max_len=35):
    text = str(text)
    return text if len(text) <= max_len else text[:max_len] + "..."


def compact_plot(fig, height=360):
    fig.update_layout(
        height=height,
        margin=dict(l=20, r=20, t=60, b=90),
        xaxis_tickangle=-45
    )
    return fig


