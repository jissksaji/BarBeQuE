@st.cache_data
def load_length_files(data_dir, primer):
    """
    Loads all the amplicon length TSV files generated by seqkit.
    This represents 'Spreadsheet 1' (The Tape Measure) which contains 
    the physical length of every single sequence in base pairs.
    """
    dfs = []
    length_dir = Path(data_dir) / "amplicon_lengths"
