@st.cache_data
def load_tax_coverage(data_dir, run_stem, primer, db):
    dfs = []
    tax_dir = Path(data_dir) / "tax_coverage"

    for file in sorted(tax_dir.glob("*.tax_coverage.tsv")):
        stem  = file.stem.replace(".tax_coverage", "")
        parts = stem.split("--")
        file_run_stem = parts[0].rstrip("_")

        if file_run_stem != run_stem:
            continue

        tmp = pd.read_csv(
            file,
            sep="\t",
            header=None,
            names=["Taxon", "Status", "Taxid", "Color", "Rank"],
            skiprows=1
        )
        # Handle older files that don't have the Rank column
        tmp["Rank"] = tmp["Rank"].fillna("species")

        tmp["primer"] = primer
        tmp["db"]     = db
        tmp["taxon"]  = parts[1] if len(parts) > 1 else "Unknown"
        dfs.append(tmp)

    if not dfs:
        return pd.DataFrame(columns=["Taxon", "Status", "Taxid", "Color", "Rank", "primer", "db", "taxon"])

    return pd.concat(dfs, ignore_index=True)


@st.cache_data
def get_coverage_df(tax_df):
    coverage_rows = []
    for (primer, rank), group in tax_df.groupby(["primer", "Rank"]):
        status_counts = group["Status"].value_counts()
        pass_count = int(status_counts.get("OK", 0))
        fail_count = int(status_counts.get("FAIL", 0))
        no_data    = int(status_counts.get("NO_DATA", 0))
        total_db   = pass_count + fail_count
        coverage   = round(pass_count / total_db * 100, 1) if total_db > 0 else 0.0
        coverage_rows.append({
            "primer":     primer,
            "Rank":       rank,
            "pass_count": pass_count,
            "fail_count": fail_count,
            "no_data":    no_data,
            "coverage":   coverage
        })
    return pd.DataFrame(coverage_rows)


