@st.cache_data
def load_length_files(data_dir, run_stem, primer, db):
    """
    Loads all the amplicon length TSV files generated by seqkit.
    This represents 'Spreadsheet 1' (The Tape Measure) which contains
    the physical length of every single sequence in base pairs.
    """
    dfs = []
    length_dir = Path(data_dir) / "amplicon_lengths"
    if not length_dir.exists():
        return pd.DataFrame()
    for file in sorted(length_dir.glob("*.tsv")):
        stem = file.stem.replace(".amplicon_lengths", "")
        if stem != run_stem:
            continue

        tmp = pd.read_csv(file, sep="\t", header=None, names=["header", "length"])
        tmp["primer"] = primer
        tmp["db"] = db
        dfs.append(tmp)
    if not dfs:
        return pd.DataFrame()
    return pd.concat(dfs, ignore_index=True)

