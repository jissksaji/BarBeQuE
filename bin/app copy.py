def load_tsv_files(outdir):
    """
    Loads all the consensus TSV files generated by the crabs/vsearch steps.
    These files represent 'Spreadsheet 2' (The Name Tag) which assigns 
    a taxonomy (species/genus/etc.) to each clustered sequence.
    """
    dfs = []
    consensus_dir = Path(outdir) / "consensus"
    if not consensus_dir.exists():
        st.error(f"Directory not found: {consensus_dir}")
        st.stop()
    for file in sorted(Path(consensus_dir).glob("*.cluster_consensus.tsv")):
        tmp = pd.read_csv(
            file,
            sep="\t",
            header=None,
            names=COLUMNS,
            dtype=DTYPES
        )
        tmp["accession_name"] = "Unknown"
        tmp["primer"] = Path(file.stem).stem

        dfs.append(tmp)

    if not dfs:
        return pd.DataFrame(columns=COLUMNS + ["primer"])

    return pd.concat(dfs, ignore_index=True)


def most_common(series, default="NA"):
    series = series.dropna()
    return series.value_counts().idxmax() if len(series) > 0 else default


def clean_taxon_name(name, rank=None):
    if pd.isna(name):
        return "Unknown"

    name = str(name).split(";")[0].strip()

    if rank == "genus":
        return name.split()[0] if name else "Unknown"

    if rank == "species":
        parts = name.split()
        return " ".join(parts[:2]) if len(parts) >= 2 else name

    return name


def shorten(text, max_len=35):
    text = str(text)
    return text if len(text) <= max_len else text[:max_len] + "..."


def compact_plot(fig, height=360):
    fig.update_layout(
        height=height,
        margin=dict(l=20, r=20, t=60, b=90),
        xaxis_tickangle=-45
    )
    return fig


